//! Phrase model, seed library and Han ⇄ Jyutping alignment.
//!
//! The seed library lives in `assets/phrases.json` and is embedded at compile
//! time so the app works offline out of the box. Users can add / edit /
//! delete phrases at runtime; those live in `localStorage` under
//! `singsin_phrases`.

use serde::{Deserialize, Serialize};
use wasm_bindgen::JsValue;

use super::phonetics::{DrillPass, MistakeRow};

/// A single practice phrase.
///
/// The first five fields mirror the on-disk `phrases.json` format exactly, so
/// a user's exported file can be dropped back into the project unchanged.
/// The optional extras are only written when present.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Phrase {
    pub id: i64,
    pub category: String,
    pub en: String,
    pub han: String,
    pub jyutping: String,

    /// Spoken (colloquial) Jyutping when it differs from the dictionary form.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub spoken_jyutping: Option<String>,

    /// Free-form user note.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub notes: Option<String>,

    /// Optional LLM-enriched notes (MiniMax).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rich: Option<RichNotes>,
}

/// Bespoke notes generated by the optional MiniMax enrichment step.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct RichNotes {
    #[serde(default)]
    pub sandhi: Vec<String>,
    #[serde(default)]
    pub mistakes: Vec<MistakeRow>,
    #[serde(default)]
    pub drills: Vec<DrillPass>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub takeaway: Option<String>,
}

/// The bundled phrase library.
pub fn seed_phrases() -> Vec<Phrase> {
    match serde_json::from_str::<Vec<Phrase>>(include_str!("../../assets/phrases.json")) {
        Ok(v) => v,
        Err(e) => {
            web_sys::console::error_1(&JsValue::from_str(&format!("SingSin: seed library is invalid: {e}")));
            Vec::new()
        }
    }
}

/// The default `spoken_jyutping` override for a phrase, if the seed library
/// (or a curated override) declares one.
pub fn seed_spoken_jyutping(id: i64) -> Option<&'static str> {
    match id {
        2 => Some("ngo5 zyu6 hai2 ho4 laan1"),
        _ => None,
    }
}

/// True when the string is a CJK ideograph.
pub fn is_han(s: &str) -> bool {
    s.chars().next().map(|c| {
        let v = c as u32;
        (0x3400..=0x4DBF).contains(&v)   // extension A
            || (0x4E00..=0x9FFF).contains(&v) // unified ideographs
            || (0xF900..=0xFAFF).contains(&v) // compatibility ideographs
            || (0x20000..=0x2A6DF).contains(&v) // extension B
    }).unwrap_or(false)
}

/// Split the Chinese text into "spoken units": one unit per Han character,
/// one unit per run of Latin letters / digits.
pub fn han_units(han: &str) -> Vec<String> {
    let mut units: Vec<String> = Vec::new();
    let mut latin = String::new();

    let flush = |latin: &mut String, units: &mut Vec<String>| {
        if !latin.is_empty() {
            units.push(std::mem::take(latin));
        }
    };

    for ch in han.chars() {
        if is_han(&ch.to_string()) {
            flush(&mut latin, &mut units);
            units.push(ch.to_string());
        } else if ch.is_alphanumeric() {
            latin.push(ch);
        } else {
            flush(&mut latin, &mut units);
        }
    }
    flush(&mut latin, &mut units);
    units
}

/// Pair every spoken unit with its Jyutping token.
///
/// Handles the common cases where the counts line up (including phrases that
/// embed a Latin name such as `Jacob`), and degrades gracefully otherwise.
pub fn align(han: &str, jyutping: &str) -> Vec<(String, String)> {
    let units = han_units(han);
    let tokens: Vec<String> = jyutping
        .split_whitespace()
        .filter(|t| !t.is_empty())
        .map(|t| t.to_string())
        .collect();

    if units.len() == tokens.len() {
        return units.into_iter().zip(tokens).collect();
    }

    let han_only: Vec<String> = units.iter().filter(|u| is_han(u)).cloned().collect();
    if han_only.len() == tokens.len() {
        return han_only.into_iter().zip(tokens).collect();
    }

    // Last resort: pair positionally and pad whichever side runs out.
    let n = units.len().min(tokens.len());
    let mut out: Vec<(String, String)> = units
        .into_iter()
        .take(n)
        .zip(tokens.iter().take(n).cloned())
        .collect();
    for t in tokens.into_iter().skip(n) {
        out.push((String::new(), t));
    }
    out
}

